/* Age-Less Medicine demo: English / Spanish switch.
   Spanish copy lives in js/i18n-es.js (generated by build.py from i18n_es.py).
   The choice is remembered in localStorage ("al-lang", the same key the shop uses),
   can be forced with ?lang=es or ?lang=en, and is carried to the shop link. */
(function () {
  "use strict";
  var ES = window.AL_ES || {};
  var KEY = "al-lang";
  var ATTRS = ["aria-label", "alt", "placeholder", "title"];
  var params = new URLSearchParams(location.search);
  var lang = params.get("lang");
  if (lang !== "es" && lang !== "en") { try { lang = localStorage.getItem(KEY); } catch (e) {} }
  if (lang !== "es") lang = "en";

  function norm(s) { return String(s).replace(/\u00a0/g, " ").replace(/\u2011/g, "-").replace(/\s+/g, " ").trim(); }
  function t(s) { if (lang !== "es") return s; var v = ES[norm(s)]; return v == null ? s : v; }

  var textOrig = new WeakMap(), attrOrig = new WeakMap(), titleOrig = document.title;
  function doText(node) {
    if (!textOrig.has(node)) textOrig.set(node, node.nodeValue);
    var o = textOrig.get(node), next = o;
    if (lang === "es") {
      var v = ES[norm(o)];
      if (v != null) next = o.match(/^\s*/)[0] + v + o.match(/\s*$/)[0];
    }
    if (node.nodeValue !== next) node.nodeValue = next;
  }
  function doAttrs(el) {
    var store = attrOrig.get(el);
    if (!store) { store = {}; attrOrig.set(el, store); }
    ATTRS.forEach(function (a) {
      if (!el.hasAttribute(a)) return;
      if (!(a in store)) store[a] = el.getAttribute(a);
      var o = store[a], v = lang === "es" ? ES[norm(o)] : null;
      var next = v == null ? o : v;
      if (el.getAttribute(a) !== next) el.setAttribute(a, next);
    });
  }
  function apply(root) {
    if (!root) return;
    if (root.nodeType === 3) { doText(root); return; }
    if (root.nodeType !== 1) return;
    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) { var p = n.parentNode && n.parentNode.nodeName; return (p === "SCRIPT" || p === "STYLE" || p === "NOSCRIPT") ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT; }
    });
    var n; while ((n = w.nextNode())) doText(n);
    if (root.matches && root.matches("[aria-label],[alt],[placeholder],[title]")) doAttrs(root);
    Array.prototype.forEach.call(root.querySelectorAll("[aria-label],[alt],[placeholder],[title]"), doAttrs);
  }
  function shopLinks() {
    Array.prototype.forEach.call(document.querySelectorAll('a[href^="site/index.html"]'), function (a) {
      var u = a.getAttribute("href").split("?")[0].split("#");
      a.setAttribute("href", u[0] + "?lang=" + lang + (u[1] ? "#" + u[1] : ""));
    });
  }
  function sync() {
    document.documentElement.lang = lang;
    document.title = lang === "es" ? (ES[norm(titleOrig)] || titleOrig) : titleOrig;
    apply(document.body);
    shopLinks();
    Array.prototype.forEach.call(document.querySelectorAll("[data-lang]"), function (b) {
      b.setAttribute("aria-pressed", String(b.getAttribute("data-lang") === lang));
    });
    document.documentElement.classList.remove("lang-pending");
  }
  function setLang(next) {
    if (next !== "es" && next !== "en") return;
    lang = next;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    if (params.has("lang")) { params.set("lang", lang); history.replaceState(null, "", location.pathname + "?" + params.toString() + location.hash); }
    sync();
    document.dispatchEvent(new CustomEvent("al:lang", { detail: lang }));
  }

  window.ALi18n = { lang: function () { return lang; }, t: t, set: setLang };

  function init() {
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    sync();
    document.addEventListener("click", function (e) {
      var b = e.target.closest && e.target.closest("[data-lang]");
      if (b) { e.preventDefault(); setLang(b.getAttribute("data-lang")); }
    });
    // Translate anything the page script renders later (treatment guide, booking messages)
    new MutationObserver(function (list) {
      if (lang !== "es") return;
      list.forEach(function (m) { Array.prototype.forEach.call(m.addedNodes, apply); });
    }).observe(document.body, { childList: true, subtree: true });
  }
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", init); else init();
})();
